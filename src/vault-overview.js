// A readable, derived guide to the append-only event records in an Obsidian vault.
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const GENERATED_MARKER = '<!-- Generated by FocusDesk from event records. -->';

function field(markdown, name) {
  return markdown.match(new RegExp(`^- ${name}: (.*)$`, 'm'))?.[1]?.trim() || '';
}

function safeText(value) {
  return String(value || '').replace(/[\r\n|\[\]#]/g, ' ').replace(/\s+/g, ' ').trim();
}

function readableDuration(value) {
  const milliseconds = Number.parseInt(value, 10);
  if (!Number.isFinite(milliseconds)) return safeText(value);
  const seconds = milliseconds / 1000;
  if (seconds < 60) return `${Math.round(seconds * 10) / 10} sec`;
  const minutes = Math.floor(seconds / 60);
  const remainder = Math.round(seconds % 60);
  return `${minutes} min${remainder ? ` ${remainder} sec` : ''}`;
}

function readEvents(root, kind) {
  const folder = path.join(root, kind);
  if (!fs.existsSync(folder)) return [];
  return fs.readdirSync(folder).filter(name => /^[0-9a-f-]{36}\.md$/i.test(name)).map(name => {
    const markdown = fs.readFileSync(path.join(folder, name), 'utf8');
    return {
      id: path.basename(name, '.md'), kind,
      date: field(markdown, 'Date'), time: field(markdown, 'Time'),
      type: field(markdown, 'Event type'), status: field(markdown, 'Status'),
      taskId: field(markdown, 'Task ID'), sessionId: field(markdown, 'Session ID'),
      title: field(markdown, 'Title') || field(markdown, 'Task title'),
      activity: field(markdown, 'Activity'),
      actual: field(markdown, 'Actual active duration')
    };
  });
}

function eventLine(event) {
  const when = safeText([event.date, event.time].filter(Boolean).join(' ')) || 'Unknown time';
  const label = safeText(event.type || 'event').replace(/-/g, ' ');
  const status = event.status ? ` — ${safeText(event.status)}` : '';
  const session = event.sessionId ? ` — session ${event.sessionId.slice(0, 8)}` : '';
  const duration = event.actual ? ` — ${readableDuration(event.actual)} active` : '';
  return `- ${when}: [[FocusDesk/${event.kind}/${event.id}|${label}]]${status}${session}${duration}`;
}

function buildOverview(vaultPath) {
  const root = path.join(vaultPath, 'FocusDesk');
  const events = [...readEvents(root, 'tasks'), ...readEvents(root, 'focus')];
  events.sort((a, b) => `${a.date} ${a.time} ${a.id}`.localeCompare(`${b.date} ${b.time} ${b.id}`));
  const tasks = new Map();
  const other = [];
  for (const event of events) {
    if (!event.taskId) { other.push(event); continue; }
    if (!tasks.has(event.taskId)) tasks.set(event.taskId, []);
    tasks.get(event.taskId).push(event);
  }
  const lines = [
    GENERATED_MARKER, '', '# FocusDesk overview', '',
    '> [!info] About this note',
    '> FocusDesk builds this guide from its task and focus event files. The event files are the permanent history; this overview is refreshed automatically and can be rebuilt.', '',
    `**${events.length} events** across ${tasks.size} tasks.`, '',
    '## Tasks', ''
  ];
  if (!tasks.size) lines.push('No task events yet.', '');
  for (const [taskId, related] of tasks) {
    const title = [...related].reverse().find(event => event.title)?.title || 'Untitled task';
    lines.push(`### ${safeText(title)}`, '', `Task ID: \`${taskId}\``, '');
    for (const event of related) lines.push(eventLine(event));
    lines.push('');
  }
  lines.push('## Other activities', '');
  if (!other.length) lines.push('No description-only focus events yet.');
  else for (const event of other) lines.push(`${eventLine(event)}${event.activity ? ` — ${safeText(event.activity)}` : ''}`);
  lines.push('');
  const content = lines.join('\n');
  const filename = path.join(root, 'Overview.md');
  fs.mkdirSync(root, { recursive: true });
  if (fs.existsSync(filename)) {
    const previous = fs.readFileSync(filename, 'utf8');
    if (previous === content) return filename;
    if (!previous.startsWith(GENERATED_MARKER) &&
        !(previous.startsWith('# FocusDesk overview\n') && previous.includes('FocusDesk builds this guide from its task and focus event files.'))) {
      throw new Error('FocusDesk/Overview.md already exists and was not created by FocusDesk.');
    }
  }
  const temporary = `${filename}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, content);
    fs.renameSync(temporary, filename);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
  return filename;
}

module.exports = { buildOverview };
